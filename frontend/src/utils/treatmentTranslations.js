/**
 * Get localized display string for a given canonical treatment name.
 * Fallbacks safely to English or raw canonical string if not found.
 */
export function getTranslatedTreatmentName(name, lang = "en") {
  if (!name || typeof name !== "string") return name || "";
  const trimmed = name.trim();
  if (lang === "en" || !["mr", "hi"].includes(lang)) {
    return treatmentDictionary[trimmed]?.en || trimmed;
  }
  return treatmentDictionary[trimmed]?.[lang] || treatmentDictionary[trimmed]?.en || trimmed;
}

/**
 * Reverse lookup to get canonical treatment name from any display name or translation.
 */
export function getTreatmentCanonicalName(displayName) {
  if (!displayName || typeof displayName !== "string") return displayName || "";
  const trimmed = displayName.trim();

  // 1. Direct match with dictionary keys
  if (treatmentDictionary[trimmed]) return trimmed;

  // 2. Search by localized values
  for (const [canonical, trans] of Object.entries(treatmentDictionary)) {
    if (
      trans.en?.toLowerCase() === trimmed.toLowerCase() ||
      trans.mr?.toLowerCase() === trimmed.toLowerCase() ||
      trans.hi?.toLowerCase() === trimmed.toLowerCase()
    ) {
      return canonical;
    }
  }

  return trimmed;
}

/**
 * Multi-language treatment filtering helper.
 * Filters an array of treatment objects by query matching either translated display name (EN/MR/HI) or canonical name.
 */
export function filterTreatmentsBySearch(treatments, query, lang = "en") {
  if (!Array.isArray(treatments)) return [];
  const q = String(query || "").trim().toLowerCase();
  if (!q) return treatments;

  return treatments.filter((tItem) => {
    const canonicalName = typeof tItem === "string" ? tItem : tItem?.name || tItem?.title || "";
    const translatedName = getTranslatedTreatmentName(canonicalName, lang);
    const englishName = getTranslatedTreatmentName(canonicalName, "en");
    const category = typeof tItem === "object" ? tItem?.category || "" : "";

    return (
      canonicalName.toLowerCase().includes(q) ||
      translatedName.toLowerCase().includes(q) ||
      englishName.toLowerCase().includes(q) ||
      category.toLowerCase().includes(q)
    );
  });
}
